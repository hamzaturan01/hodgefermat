#!/usr/bin/env python3
"""
hodge_fermat.py  --  Hodge classes on Fermat varieties (Shioda's criterion)

X = X_m^n : x_0^m + ... + x_{n+1}^m = 0  in  P^{n+1},   dim X = n (n even).

Known structure (Pham, Shioda, Aoki):
  * The primitive middle cohomology H^n_prim(X, C) is a sum of 1-dimensional eigenspaces.
    Each eigenspace belongs to an alpha = (a_0,...,a_{n+1}) with:
    a_i in {1..m-1},  sum a_i = 0 (mod m).
  * <alpha> := sum a_i / m  (an integer). Hodge type (p,q), q = <alpha> - 1, p = n - q.
  * Shioda's criterion: V(alpha) yields a Q-Hodge class (type (n/2,n/2), Galois-stable)
    if and only if
        <t*alpha> = n/2 + 1   for every t in (Z/m)^*.
  * "Decomposable" alpha: alpha that can be split into pairs {a, m-a}.
    These come from classes of linear subspaces of the Fermat variety -> algebraic.
  * Indecomposable Hodge alphas are classes not explained by the linear-subspace
    method above. This alone does not prove they are non-algebraic; their
    algebraicity is a separate mathematical question.

Usage:
  python hodge_fermat.py selftest
  python hodge_fermat.py hodge 4 2            # Hodge numbers (m=4, n=2)
  python hodge_fermat.py list 6 4             # indecomposable Hodge orbits
  python hodge_fermat.py table 2 30 --n 2     # table for m=2..30
  python hodge_fermat.py table 2 24 --n 4
"""
import argparse
import sys
from collections import Counter
from itertools import combinations_with_replacement
from math import factorial, gcd


def units(m):
    return [t for t in range(1, m) if gcd(t, m) == 1]


def multiplicity(alpha):
    """Number of distinct permutations of a sorted alpha (number of ordered alphas)."""
    c = Counter(alpha)
    r = factorial(len(alpha))
    for v in c.values():
        r //= factorial(v)
    return r


def multisets(m, n):
    """All multisets with sum = 0 mod m and a_i in 1..m-1 (as sorted tuples)."""
    for alpha in combinations_with_replacement(range(1, m), n + 2):
        if sum(alpha) % m == 0:
            yield alpha


def is_hodge(alpha, m, n, U):
    target = (n // 2 + 1) * m
    for t in U:
        if sum((t * a) % m for a in alpha) != target:
            return False
    return True


def is_decomposable(alpha, m):
    """Is there a perfect matching into pairs {a, m-a}?"""
    c = Counter(alpha)
    for a, k in c.items():
        b = m - a
        if a == b:
            if k % 2:
                return False
        elif c.get(b, 0) != k:
            return False
    return True


def galois_orbit_rep(alpha, m, U):
    return min(tuple(sorted((t * a) % m for a in alpha)) for t in U)


def hodge_numbers(m, n):
    """Primitive Hodge numbers h^{p,q}_prim, q = <alpha>-1."""
    if m < 2:
        raise ValueError("m >= 2 required")
    if n % 2 or n < 2:
        raise ValueError("n must be even and >= 2")
    h = Counter()
    for alpha in multisets(m, n):
        q = sum(alpha) // m - 1
        h[(n - q, q)] += multiplicity(alpha)
    return dict(sorted(h.items()))


def analyse(m, n):
    """(primitive dimension, |B|, |D|, dict of indecomposable orbits)

    B = alphas satisfying Shioda's criterion (Hodge), D = the decomposable ones.
    All counts are numbers of ordered alphas.
    """
    if m < 2:
        raise ValueError("m >= 2 required")
    if n % 2 or n < 2:
        raise ValueError("n must be even and >= 2")
    U = units(m)
    prim = 0
    hodge = 0
    decomp = 0
    bad = {}  # orbit representative -> number of ordered alphas in that orbit family
    for alpha in multisets(m, n):
        mult = multiplicity(alpha)
        prim += mult
        if not is_hodge(alpha, m, n, U):
            continue
        hodge += mult
        if is_decomposable(alpha, m):
            decomp += mult
        else:
            rep = galois_orbit_rep(alpha, m, U)
            bad.setdefault(rep, 0)
            bad[rep] += mult
    # A Galois orbit may contain several multisets: their multiplicities are summed above.
    return prim, hodge, decomp, bad


def cmd_hodge(m, n):
    print(f"X_{m}^{n}: primitive Hodge numbers")
    tot = 0
    for (p, q), v in hodge_numbers(m, n).items():
        print(f"  h^({p},{q})_prim = {v}")
        tot += v
    print(f"  total primitive dimension = {tot}")


def cmd_list(m, n, limit):
    prim, hodge, decomp, bad = analyse(m, n)
    print(f"X_{m}^{n}: primitive dim={prim}, Hodge classes={hodge}, "
          f"decomposable (linear subspace)={decomp}, indecomposable={hodge - decomp}")
    if not bad:
        print("No indecomposable Hodge classes: all Hodge classes are generated by linear subspaces.")
        return
    print(f"Indecomposable Galois-orbit representatives ({len(bad)} total, first {limit}):")
    for i, (rep, cnt) in enumerate(sorted(bad.items())):
        if i >= limit:
            print("  ...")
            break
        print(f"  alpha={rep}  (this orbit family: {cnt} ordered alphas)")


def cmd_table(mlo, mhi, n):
    print(f"n={n}  (X_m^n: x_0^m+...+x_{n+1}^m=0)")
    hdr = f"{'m':>3} {'prim':>9} {'Hodge':>7} {'decomp.':>7} {'indecomp.':>9}"
    if n == 2:
        hdr += f" {'rho':>6}"
    print(hdr)
    for m in range(mlo, mhi + 1):
        prim, hodge, decomp, _ = analyse(m, n)
        row = f"{m:>3} {prim:>9} {hodge:>7} {decomp:>7} {hodge - decomp:>9}"
        if n == 2:
            row += f" {hodge + 1:>6}"
        print(row)


def selftest():
    # Invalid parameters must be rejected explicitly.
    for fn in (hodge_numbers, analyse):
        for bad_m, n in ((1, 2), (0, 2)):
            try:
                fn(bad_m, n)
            except ValueError:
                pass
            else:
                raise AssertionError(f"{fn.__name__} did not reject m={bad_m}")
        for m, bad_n in ((4, 1), (4, 0), (4, 3)):
            try:
                fn(m, bad_n)
            except ValueError:
                pass
            else:
                raise AssertionError(f"{fn.__name__} did not reject n={bad_n}")

    # K3 (Fermat quartic surface): h^{2,0}=1, h^{1,1}_prim=19, h^{0,2}=1
    assert hodge_numbers(4, 2) == {(0, 2): 1, (1, 1): 19, (2, 0): 1}
    # Known Picard numbers (rho = Hodge + 1, n = 2)
    for m, rho in {3: 7, 4: 20, 5: 37, 7: 91}.items():
        prim, hodge, decomp, bad = analyse(m, 2)
        assert hodge + 1 == rho, (m, hodge + 1, rho)
    # Decomposable => Hodge (consistency)
    for m in range(2, 13):
        for n in (2, 4):
            U = units(m)
            for a in multisets(m, n):
                if is_decomposable(a, m):
                    assert is_hodge(a, m, n, U)
    # m prime => no indecomposable classes (Pham/Ran/Shioda)
    for m in (3, 5, 7, 11):
        assert analyse(m, 2)[1] == analyse(m, 2)[2]
    print("selftest OK")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("selftest")
    p = sub.add_parser("hodge"); p.add_argument("m", type=int); p.add_argument("n", type=int)
    p = sub.add_parser("list"); p.add_argument("m", type=int); p.add_argument("n", type=int)
    p.add_argument("--limit", type=int, default=40)
    p = sub.add_parser("table"); p.add_argument("mlo", type=int); p.add_argument("mhi", type=int)
    p.add_argument("--n", type=int, default=2)
    a = ap.parse_args()
    if a.cmd == "selftest":
        selftest()
    elif a.cmd == "hodge":
        cmd_hodge(a.m, a.n)
    elif a.cmd == "list":
        cmd_list(a.m, a.n, a.limit)
    elif a.cmd == "table":
        cmd_table(a.mlo, a.mhi, a.n)


if __name__ == "__main__":
    sys.exit(main())
